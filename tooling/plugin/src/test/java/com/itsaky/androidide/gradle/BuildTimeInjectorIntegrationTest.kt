    // ---- 7) parsePreheatBreakpoints -> renderIdeDebuggerBootstrapKt 端到端 ----

    @Test
    fun `integration - end-to-end parsePreheatBreakpoints then renderIdeDebuggerBootstrapKt`() {
        // 模拟 Gradle property -> parse -> render
        val prop = "src=src/main/java/MainActivity.kt:42:8;src=src/main/java/Other.kt:100:0"
        val preheat = parsePreheatBreakpoints(prop)
        assertEquals(2, preheat.size)
        assertEquals("src/main/java/MainActivity.kt", preheat[0].sourceFile)
        assertEquals(42, preheat[0].line)
        assertEquals(8, preheat[0].column)
        assertEquals("src/main/java/Other.kt", preheat[1].sourceFile)
        assertEquals(100, preheat[1].line)
        assertEquals(0, preheat[1].column)

        val content = renderIdeDebuggerBootstrapKt(
            ideVersion = "1.0.0",
            localServerName = "test",
            extras = "sdk=33",
            buildTimestampMs = 1L,
            preheatBreakpoints = preheat,
        )
        // parse + render 后, bp 真的进了生成文件
        assertTrue(content.contains("sourceFile = \"src/main/java/MainActivity.kt\""))
        assertTrue(content.contains("line = 42"))
        assertTrue(content.contains("column = 8"))
        assertTrue(content.contains("sourceFile = \"src/main/java/Other.kt\""))
        assertTrue(content.contains("line = 100"))
    }

    // ---- 内部辅助 ----

    private fun diffIgnoring(a: String, b: String, marker: String): List<String> {
        val linesA = a.lines()
        val linesB = b.lines()
        val diffs = mutableListOf<String>()
        for (i in 0 until minOf(linesA.size, linesB.size)) {
            if (linesA[i] != linesB[i]) {
                if (linesA[i].contains(marker) && linesB[i].contains(marker)) {
                    // same marker, just different value
                    continue
                }
                diffs.add("line $i: A='${linesA[i]}' B='${linesB[i]}'")
            }
        }
        if (linesA.size != linesB.size) {
            diffs.add("line count: A=${linesA.size} B=${linesB.size}")
        }
        return diffs
    }
