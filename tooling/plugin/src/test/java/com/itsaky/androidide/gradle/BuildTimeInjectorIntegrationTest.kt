    // ---- 1) 完整生成产物: 模拟子项目 10 的 generateIdeDebuggerBootstrapSource 写文件 ----

    @Test
    fun `integration - write generated file to expected package path`() {
        val projectDir = tempFolder.newFolder("sample-host-app")
        val generatedDir = File(projectDir, "build/generated/source/ide_debugger/debug/kotlin")
        generatedDir.mkdirs()

        val group = "com.example.app"
        val name = "myapp"
        val sdkInt = 33
        val preheat = listOf(
            RenderedBreakpoint("app/src/main/java/MainActivity.kt", 42, 8),
            RenderedBreakpoint("app/src/main/java/OtherActivity.kt", 100, 0),
        )
        val content = renderIdeDebuggerBootstrapKt(
            ideVersion = "1.0.0",
            localServerName = computeLocalServerName(group, name),
            extras = "sdk=$sdkInt",
            buildTimestampMs = 1_700_000_000_000L,
            preheatBreakpoints = preheat,
        )
        val targetFile = File(
            generatedDir,
            "com/itsaky/androidide/zerostudio/ide/debugger/host/generated/IdeDebuggerBootstrap.kt"
        )
        targetFile.parentFile.mkdirs()
        targetFile.writeText(content)

        assertTrue("file should exist: ${targetFile.absolutePath}", targetFile.exists())
        assertTrue("file should be non-empty", targetFile.length() > 0)

        val text = targetFile.readText()
        // 验证 4 段结构都在
        assertTrue("auto-gen header", text.contains("AUTO-GENERATED by IdeDebuggerInitScriptPlugin"))
        assertTrue("package", text.contains("package com.itsaky.androidide.zerostudio.ide.debugger.host.generated"))
        assertTrue("import Application", text.contains("import android.app.Application"))
        assertTrue("import HostAttachAgentBootstrap", text.contains("import com.itsaky.androidide.zerostudio.ide.debugger.host.HostAttachAgentBootstrap"))
        assertTrue("object name", text.contains("object IdeDebuggerBootstrap"))
        assertTrue("IDE_DEBUGGER_VERSION", text.contains("const val IDE_DEBUGGER_VERSION: String"))
        assertTrue("LOCAL_SERVER_NAME", text.contains("const val LOCAL_SERVER_NAME: String"))
        assertTrue("HELLO_PROTOCOL_EXTRA_FIELDS", text.contains("const val HELLO_PROTOCOL_EXTRA_FIELDS: String"))
        assertTrue("BUILD_TIMESTAMP_MS", text.contains("const val BUILD_TIMESTAMP_MS: Long = 1700000000000"))
        assertTrue("data class", text.contains("data class BreakpointLocation("))
        assertTrue("sourceFile", text.contains("val sourceFile: String"))
        assertTrue("line", text.contains("val line: Int"))
        assertTrue("column", text.contains("val column: Int = 0"))
        assertTrue("PREHEAT_BREAKPOINTS", text.contains("val PREHEAT_BREAKPOINTS: List<BreakpointLocation>"))
        assertTrue("init()", text.contains("fun init(application: Application)"))
        assertTrue("@JvmStatic", text.contains("@JvmStatic"))
        assertTrue("@Synchronized", text.contains("@Synchronized"))
        assertTrue("init 调用 startReverseConnectThread", text.contains("HostAttachAgentBootstrap.startReverseConnectThread"))
    }

    // ---- 2) 真实 IDE 端常量注入 (BuildInfo.VERSION_NAME + group/name + sdkInt) ----

