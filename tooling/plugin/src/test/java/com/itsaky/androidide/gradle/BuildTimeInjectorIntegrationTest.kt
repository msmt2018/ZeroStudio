    // ---- 3) 真实预热 bp 列表 (多个文件 + 每行每列) ----

    @Test
    fun `integration - real preheat breakpoints with multi-file line column`() {
        val preheat = listOf(
            RenderedBreakpoint("src/main/java/A.kt", 10, 0),
            RenderedBreakpoint("src/main/java/B.kt", 20, 4),
            RenderedBreakpoint("src/main/java/C.kt", 30, 12),
            RenderedBreakpoint("src/main/java/D.kt", 40, 0),
        )
        val content = renderIdeDebuggerBootstrapKt(
            ideVersion = "1.0.0",
            localServerName = "test-server",
            extras = "sdk=33",
            buildTimestampMs = 1L,
            preheatBreakpoints = preheat,
        )
        // 每个 bp 的 line + column 都在
        assertTrue("A.kt:10:0", content.contains("sourceFile = \"src/main/java/A.kt\""))
        assertTrue("A line=10", content.contains("line = 10"))
        assertTrue("A col=0", content.contains("column = 0"))
        assertTrue("B line=20 col=4", content.contains("line = 20") && content.contains("column = 4"))
        assertTrue("C line=30 col=12", content.contains("line = 30") && content.contains("column = 12"))
        assertTrue("D line=40 col=0", content.contains("line = 40") && content.contains("column = 0"))
        // 用了 listOf 而非 emptyList
        assertTrue("uses listOf for non-empty", content.contains("listOf("))
        assertFalse("does not use emptyList for non-empty", content.contains("emptyList()"))
    }

