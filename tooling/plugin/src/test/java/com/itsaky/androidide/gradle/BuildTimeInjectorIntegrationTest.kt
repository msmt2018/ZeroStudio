        )
    }

    // ---- 5) 生成产物在多次重新生成时都稳定 (除 buildTs 外) ----

    @Test
    fun `integration - regenerating gives same content except build timestamp`() {
        val group = "com.x"
        val name = "y"
        val preheat = listOf(RenderedBreakpoint("a", 1, 0))
        val content1 = renderIdeDebuggerBootstrapKt(
            ideVersion = "1.0.0",
            localServerName = computeLocalServerName(group, name),
            extras = "sdk=33",
            buildTimestampMs = 1_000L,
            preheatBreakpoints = preheat,
        )
        val content2 = renderIdeDebuggerBootstrapKt(
            ideVersion = "1.0.0",
            localServerName = computeLocalServerName(group, name),
            extras = "sdk=33",
            buildTimestampMs = 2_000L,
            preheatBreakpoints = preheat,
        )
        // 唯一差别: BUILD_TIMESTAMP_MS
        val diff = diffIgnoring(content1, content2, "BUILD_TIMESTAMP_MS: Long = ")
        assertEquals("only BUILD_TIMESTAMP_MS should differ", 0, diff.size)
    }

