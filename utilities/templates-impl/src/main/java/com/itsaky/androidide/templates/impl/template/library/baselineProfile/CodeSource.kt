package com.itsaky.androidide.templates.impl.template.library.baselineProfile

import com.itsaky.androidide.templates.base.AndroidModuleTemplateBuilder

/**
 * 生成 [BaselineProfileGenerator] 源文件。
 *
 * 该文件是 androidx.baselineprofile 插件生成基线性能文件的核心入口。
 * 默认使用 application 变体 + `CompilationMode.DEFAULT` + `StartupMode.COLD`。
 */
internal fun AndroidModuleTemplateBuilder.baselineProfileGeneratorSrc(): String {
  val pkg = data.packageName
  val appId = "androidx.baselineprofile.generated.reserved"
  return """
package $pkg

import androidx.benchmark.macro.junit4.BaselineProfileRule
import androidx.test.ext.junit.runners.AndroidJUnit4
import androidx.test.filters.LargeTest
import androidx.test.platform.app.InstrumentationRegistry
import androidx.test.uiautomator.UiDevice
import org.junit.Rule
import org.junit.Test
import org.junit.runner.RunWith

/**
 * 启动基线性能生成。
 *
 * Generated by ZeroStudio baseline profile template.
 */
@RunWith(AndroidJUnit4::class)
@LargeTest
class BaselineProfileGenerator {

    @get:Rule
    val rule = BaselineProfileRule()

    @Test
    fun generate() {
        // 此处填写被测 app 包名（applicationId）
        rule.collect(
            packageName = "$appId",
            maxIterations = 5,
            stableIterations = 3,
        ) {
            // 在这里驱动被测 app 完成关键用户旅程
            // 此处仅示例启动到主页：
            val device = UiDevice.getInstance(InstrumentationRegistry.getInstrumentation())
            device.pressHome()
        }
    }
}
"""
}

/**
 * 生成 [StartupBenchmarks] 源文件。
 *
 * 通过 `androidx.benchmark.macro.junit4` 提供启动性能指标采集。
 */
internal fun AndroidModuleTemplateBuilder.startupBenchmarksSrc(): String {
  val pkg = data.packageName
  val appId = "androidx.baselineprofile.generated.reserved"
  return """
package $pkg

import androidx.benchmark.macro.BaselineProfileMode
import androidx.benchmark.macro.CompilationMode
import androidx.benchmark.macro.StartupMode
import androidx.benchmark.macro.StartupTimingMetric
import androidx.benchmark.macro.junit4.MacrobenchmarkRule
import androidx.test.ext.junit.runners.AndroidJUnit4
import androidx.test.filters.LargeTest
import org.junit.Rule
import org.junit.Test
import org.junit.runner.RunWith

/**
 * 启动性能基准测试。
 *
 * Generated by ZeroStudio baseline profile template.
 */
@RunWith(AndroidJUnit4::class)
@LargeTest
class StartupBenchmarks {

    @get:Rule
    val rule = MacrobenchmarkRule()

    @Test
    fun startupCompilationNone() = benchmark(CompilationMode.None(), StartupMode.COLD)

    @Test
    fun startupCompilationBaselineProfiles() = benchmark(
        CompilationMode.DEFAULT,
        StartupMode.COLD,
        BaselineProfileMode.Require
    )

    private fun benchmark(
        compilationMode: CompilationMode,
        startupMode: StartupMode,
        baselineProfileMode: BaselineProfileMode = BaselineProfileMode.Disable,
    ) {
        rule.measureRepeated(
            packageName = "$appId",
            metrics = listOf(StartupTimingMetric()),
            compilationMode = compilationMode,
            startupMode = startupMode,
            baselineProfileMode = baselineProfileMode,
            iterations = 5,
            setupBlock = {
                pressHome()
            },
        ) {
            // start your app explicitly: startActivity(...)
        }
    }
}
"""
}
