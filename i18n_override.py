def apply_overrides(locale, mapping):
    path = os.path.join(RES_DIR, f"values-{locale}", "strings.xml")
    with open(path, "r", encoding="utf-8") as f:
        content = f.read()
    for key, value in mapping.items():
        # If value already contains XML entities like &amp; / &lt; / &gt;,
        # unescape them first so we can re-escape consistently.
        if "&amp;" in value or "&lt;" in value or "&gt;" in value:
            value = (
                value.replace("&amp;", "&")
                     .replace("&lt;", "<")
                     .replace("&gt;", ">")
            )
        esc = value.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
        # Replace the <string name="KEY">VALUE</string> line.
        pattern = re.compile(
            r'(<string\s+name="' + re.escape(key) + r'">)[^<]*(</string>)'
        )
        new_content, n = pattern.subn(r'\1' + esc + r'\2', content)
        if n == 0:
            print(f"  ! could not find {key} in {locale}")
            return
        content = new_content
    with open(path, "w", encoding="utf-8") as f:
        f.write(content)
    print(f"overrode {locale} ({len(mapping)} keys)")

def main():
    for locale, mapping in OVERRIDES.items():
        apply_overrides(locale, mapping)

if __name__ == "__main__":
    main()
